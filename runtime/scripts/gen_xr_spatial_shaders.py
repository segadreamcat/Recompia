"""Compile the spatial overlay shaders; accepts glslc and spirv-val paths, writes only its own generated header."""
from pathlib import Path
import subprocess, struct, sys, tempfile
root = Path(__file__).resolve().parents[1]
parts = ['// GENERATED by scripts/gen_xr_spatial_shaders.py; SPIR-V for Vulkan 1.3.\n']
with tempfile.TemporaryDirectory() as temp:
    for stage, name in [('vert', 'kSpatialVert'), ('frag', 'kSpatialFrag')]:
        out = Path(temp) / (stage + '.spv')
        subprocess.run([sys.argv[1], '-O', '--target-env=vulkan1.3', str(root / ('src/gfx/xr/spatial.' + stage)), '-o', str(out)], check=True)
        subprocess.run([sys.argv[2], '--target-env', 'vulkan1.3', str(out)], check=True)
        data = out.read_bytes(); words = struct.unpack('<' + 'I' * (len(data)//4), data)
        parts.append('constexpr uint32_t ' + name + '[] = {\n')
        parts.extend('    ' + ', '.join(f'0x{v:08x}' for v in words[i:i+8]) + ',\n' for i in range(0,len(words),8))
        parts.append('};\n')
(root / 'src/gfx/xr/xr_spatial_shaders.inc').write_bytes(''.join(parts).replace('\n','\r\n').encode())
